import CoreGraphics
import Foundation

/// High-level tailored scenes built around the 7 daily apps.
public enum SceneKind: String, Equatable, Codable, Sendable {
    case dropAndSend = "drop-and-send"
    case devSplit = "dev-split"
    case swapRightBrowser = "swap-right-browser"
    case dualBrowser = "dual-browser"
    case grokDrawer = "grok-drawer"

    public var label: String {
        switch self {
        case .dropAndSend: return "Drop & Send"
        case .devSplit: return "Dev Split"
        case .swapRightBrowser: return "Swap Right Browser"
        case .dualBrowser: return "Dual Browser Split"
        case .grokDrawer: return "Grok Bot Drawer"
        }
    }
}

/// One window placement instruction generated by `ScenePlanner`.
public struct WindowTarget: Equatable, Sendable {
    public let app: ManagedApp
    public let frame: CGRect
    public let displayID: UInt32
    public let autoOpenDownloadsIfEmpty: Bool

    public init(
        app: ManagedApp,
        frame: CGRect,
        displayID: UInt32,
        autoOpenDownloadsIfEmpty: Bool = false
    ) {
        self.app = app
        self.frame = frame
        self.displayID = displayID
        self.autoOpenDownloadsIfEmpty = autoOpenDownloadsIfEmpty
    }
}

/// Complete executable plan for a scene.
public struct ScenePlan: Equatable, Sendable {
    public let scene: SceneKind
    public let targets: [WindowTarget]
    public let focusApp: ManagedApp
    public let summary: String

    public init(scene: SceneKind, targets: [WindowTarget], focusApp: ManagedApp, summary: String) {
        self.scene = scene
        self.targets = targets
        self.focusApp = focusApp
        self.summary = summary
    }
}

/// Decision for mnemonic app summon-or-cycle (⌃⌥T/Z/C/S/F).
public enum SummonDecision: Equatable, Sendable {
    case unavailable(ManagedApp)
    case launch(ManagedApp)
    case activate(ManagedApp, autoOpenDownloadsIfEmpty: Bool)
    case cycleWindows(ManagedApp)
    case hideAndRestorePrevious(ManagedApp)
}

/// Pure scene and browser-cycling planner.
public enum ScenePlanner {
    /// Picks the active browser for Dev Split, respecting installed browsers when provided.
    public static func activeBrowser(
        frontmostBundleID: String?,
        lastRightBrowser: ManagedApp = .zen,
        runningBundleIDs: Set<String>,
        installedApps: Set<ManagedApp>? = nil
    ) -> ManagedApp {
        let allowed = allowedBrowsers(installedApps: installedApps)
        if let frontApp = ManagedApp.from(bundleID: frontmostBundleID), allowed.contains(frontApp) {
            return frontApp
        }
        if allowed.contains(lastRightBrowser) && runningBundleIDs.contains(lastRightBrowser.bundleID) {
            return lastRightBrowser
        }
        for browser in allowed where runningBundleIDs.contains(browser.bundleID) {
            return browser
        }
        if allowed.contains(lastRightBrowser) { return lastRightBrowser }
        return allowed.first ?? .safari
    }

    /// Advances the right browser in `Zen → Chrome → Safari → Zen` order, skipping uninstalled browsers when `installedApps` is given.
    public static func nextRightBrowser(
        after current: ManagedApp,
        installedApps: Set<ManagedApp>? = nil
    ) -> ManagedApp {
        let cycle = allowedBrowsers(installedApps: installedApps)
        guard !cycle.isEmpty else { return .safari }
        if let idx = cycle.firstIndex(of: current) {
            return cycle[(idx + 1) % cycle.count]
        }
        // If current isn't in the filtered cycle, pick the next installed browser after current's canonical position.
        if let canonicalIdx = ManagedApp.browsers.firstIndex(of: current) {
            let count = ManagedApp.browsers.count
            for offset in 1...count {
                let candidate = ManagedApp.browsers[(canonicalIdx + offset) % count]
                if cycle.contains(candidate) { return candidate }
            }
        }
        return cycle[0]
    }

    /// Chooses the secondary browser for Dual Browser Split (`Zen` left + `Chrome` or `Safari` right).
    public static func dualBrowserRight(
        runningBundleIDs: Set<String>,
        preferredRight: ManagedApp? = nil,
        installedApps: Set<ManagedApp>? = nil
    ) -> ManagedApp {
        let candidates: [ManagedApp] = [.chrome, .safari].filter { app in
            installedApps.map { $0.contains(app) } ?? true
        }
        if let preferredRight, candidates.contains(preferredRight),
           runningBundleIDs.contains(preferredRight.bundleID) {
            return preferredRight
        }
        for candidate in candidates where runningBundleIDs.contains(candidate.bundleID) {
            return candidate
        }
        return candidates.first ?? .safari
    }

    /// **Drop & Send (`⌃⌥W`)**: Finder left 42% + WhatsApp right 58% (clamped ≥58% & ≥680px).
    public static func dropAndSend(
        profile: DisplayProfile,
        padding: LayoutPadding = .zero
    ) -> ScenePlan {
        let display = profile.display(for: .companion)
        let pair = ScreenGeometry.horizontalPair(
            leftFraction: 0.42,
            in: display.visibleFrame,
            leftConstraint: ManagedApp.finder.constraint,
            rightConstraint: ManagedApp.whatsapp.constraint,
            padding: padding
        )
        return ScenePlan(
            scene: .dropAndSend,
            targets: [
                WindowTarget(
                    app: .finder,
                    frame: pair.left,
                    displayID: display.id,
                    autoOpenDownloadsIfEmpty: true
                ),
                WindowTarget(
                    app: .whatsapp,
                    frame: pair.right,
                    displayID: display.id
                ),
            ],
            focusApp: .whatsapp,
            summary: "Drop & Send: Finder (left) + WhatsApp (right)"
        )
    }

    /// **Dev Split (`⌃⌥1`)**: Ghostty left 48% + active browser right 52%.
    public static func devSplit(
        profile: DisplayProfile,
        browser: ManagedApp,
        padding: LayoutPadding = .zero
    ) -> ScenePlan {
        let resolvedBrowser = browser.isBrowser ? browser : .zen
        let display = profile.display(for: .devWork)
        let pair = ScreenGeometry.horizontalPair(
            leftFraction: 0.48,
            in: display.visibleFrame,
            leftConstraint: ManagedApp.ghostty.constraint,
            rightConstraint: resolvedBrowser.constraint,
            padding: padding
        )
        return ScenePlan(
            scene: .devSplit,
            targets: [
                WindowTarget(app: .ghostty, frame: pair.left, displayID: display.id),
                WindowTarget(app: resolvedBrowser, frame: pair.right, displayID: display.id),
            ],
            focusApp: .ghostty,
            summary: "Dev Split: Ghostty (48%) + \(resolvedBrowser.displayName) (52%)"
        )
    }

    /// **Swap Right Browser (`⌃⌥B`)**: Keeps Ghostty pinned left 48% and puts the next installed browser in right 52%.
    public static func swapRightBrowser(
        profile: DisplayProfile,
        currentBrowser: ManagedApp,
        installedApps: Set<ManagedApp>? = nil,
        padding: LayoutPadding = .zero
    ) -> (plan: ScenePlan, nextBrowser: ManagedApp) {
        let next = nextRightBrowser(after: currentBrowser, installedApps: installedApps)
        let display = profile.display(for: .devWork)
        let pair = ScreenGeometry.horizontalPair(
            leftFraction: 0.48,
            in: display.visibleFrame,
            leftConstraint: ManagedApp.ghostty.constraint,
            rightConstraint: next.constraint,
            padding: padding
        )
        let plan = ScenePlan(
            scene: .swapRightBrowser,
            targets: [
                WindowTarget(app: .ghostty, frame: pair.left, displayID: display.id),
                WindowTarget(app: next, frame: pair.right, displayID: display.id),
            ],
            focusApp: next,
            summary: "Swap Right Browser: Ghostty + \(next.displayName)"
        )
        return (plan, next)
    }

    /// **Dual Browser Split (`⌃⌥2`)**: Zen left 50% + Chrome or Safari right 50%.
    public static func dualBrowser(
        profile: DisplayProfile,
        rightBrowser: ManagedApp,
        padding: LayoutPadding = .zero
    ) -> ScenePlan {
        let resolvedRight = (rightBrowser == .chrome || rightBrowser == .safari) ? rightBrowser : .chrome
        let display = profile.display(for: .devWork)
        let pair = ScreenGeometry.horizontalPair(
            leftFraction: 0.50,
            in: display.visibleFrame,
            leftConstraint: ManagedApp.zen.constraint,
            rightConstraint: resolvedRight.constraint,
            padding: padding
        )
        return ScenePlan(
            scene: .dualBrowser,
            targets: [
                WindowTarget(app: .zen, frame: pair.left, displayID: display.id),
                WindowTarget(app: resolvedRight, frame: pair.right, displayID: display.id),
            ],
            focusApp: .zen,
            summary: "Dual Browser: Zen (50%) + \(resolvedRight.displayName) (50%)"
        )
    }

    /// **Grok Bot Slide-Over Drawer (`⌃⌥G`)**: Right 38% drawer clamped ≥500px for Electron.
    public static func grokDrawer(
        profile: DisplayProfile,
        padding: LayoutPadding = .zero
    ) -> ScenePlan {
        let display = profile.display(for: .companion)
        let frame = ScreenGeometry.frame(
            for: .rightDrawer(widthFraction: 0.38, minWidth: ManagedApp.grokBot.constraint.minWidth),
            in: display.visibleFrame,
            constraint: ManagedApp.grokBot.constraint,
            padding: padding
        )
        return ScenePlan(
            scene: .grokDrawer,
            targets: [
                WindowTarget(app: .grokBot, frame: frame, displayID: display.id),
            ],
            focusApp: .grokBot,
            summary: "Grok Bot Drawer (right 38%)"
        )
    }

    /// Decides what mnemonic summon-or-cycle should do for `app`, gracefully no-oping when uninstalled.
    public static func summonDecision(
        for app: ManagedApp,
        isInstalled: Bool = true,
        isRunning: Bool,
        isFrontmost: Bool,
        standardWindowCount: Int
    ) -> SummonDecision {
        guard isInstalled || isRunning else { return .unavailable(app) }
        guard isRunning else { return .launch(app) }
        if !isFrontmost {
            return .activate(app, autoOpenDownloadsIfEmpty: app.constraint.autoOpenDownloadsIfEmpty)
        }
        if standardWindowCount > 1 {
            return .cycleWindows(app)
        }
        return .hideAndRestorePrevious(app)
    }

    private static func allowedBrowsers(installedApps: Set<ManagedApp>?) -> [ManagedApp] {
        guard let installedApps else { return ManagedApp.browsers }
        let filtered = ManagedApp.browsers.filter { installedApps.contains($0) }
        return filtered.isEmpty ? ManagedApp.browsers : filtered
    }
}
